N_CUSTOMERS = 60


def _seeded_customer_rows(n, seed):
    """Draws n customer feature rows from the EXACT same distribution used to
    generate the training dataset (see ml/data/generate_dataset.py), so
    seeded demo customers fall inside the range the models were trained on
    instead of skewing predictions toward saturated extremes."""
    import sys
    sys.path.append(os.path.abspath(os.path.join(os.path.dirname(__file__), '..')))
    from ml.data.generate_dataset import generate_raw_features
    df = generate_raw_features(n, seed)
    return df.to_dict('records')


def seed_core():
    from database.db import db
    from models.user import User
    from models.customer import Customer, CustomerBehavior
    from models.product import Product

    if User.query.count() > 0:
        print('Core data already seeded (users exist) - skipping seed_core().')
        return

    rng = random.Random(42)

    print('Seeding demo users...')
    customer_user = User(name='Pritam Customer', email='customer@demo.com', role='customer')
    customer_user.set_password('customer123')
    admin_user = User(name='Jordan Admin', email='admin@demo.com', role='admin')
    admin_user.set_password('admin123')
    db.session.add_all([customer_user, admin_user])
    db.session.flush()

    print(f'Seeding {len(PRODUCTS_SEED)} products...')
    for p in PRODUCTS_SEED:
        db.session.add(Product(**p))

    print(f'Seeding {N_CUSTOMERS} customers with behavior profiles...')
    now = datetime.now(timezone.utc)
    rows = _seeded_customer_rows(N_CUSTOMERS, seed=123)
    customers = []
    for i, row in enumerate(rows):
        first = FIRST_NAMES[i % len(FIRST_NAMES)]
        last = LAST_NAMES[(i // len(FIRST_NAMES)) % len(LAST_NAMES)]
        behavior_data = {
            'age': int(row['Age']),
            'gender': row['Gender'],
            'device_type': row['Device_Type'],
            'browsing_time': float(row['Browsing_Time']),
            'pages_viewed': int(row['Pages_Viewed']),
            'previous_purchases': int(row['Previous_Purchases']),
            'average_order_value': float(row['Average_Order_Value']),
            'number_of_sessions': int(row['Number_of_Sessions']),
            'cart_additions': int(row['Cart_Additions']),
            'cart_abandonments': int(row['Cart_Abandonments']),
            'days_since_last_purchase': int(row['Days_Since_Last_Purchase']),
            'customer_lifetime_value': float(row['Customer_Lifetime_Value']),
            'discount_usage': int(row['Discount_Usage']),
            'support_interactions': int(row['Support_Interactions']),
        }
        created_at = now - timedelta(days=rng.randint(1, 360))

        customer = Customer(
            name=f'{first} {last}',
            email=f'{first.lower()}.{last.lower()}@mail.com',
            age=behavior_data['age'],
            gender=behavior_data['gender'],
            device_type=behavior_data['device_type'],
            created_at=created_at,
        )
        # Link the very first seeded customer to the demo customer login,
        # so the logged-in demo customer sees a populated profile/history.
        if i == 0:
            customer.user_id = customer_user.id
            customer.name = customer_user.name
            customer.email = customer_user.email

        db.session.add(customer)
        db.session.flush()

        behavior = CustomerBehavior(customer_id=customer.id, **{
            k: v for k, v in behavior_data.items() if k not in ('age', 'gender', 'device_type')
        })
        db.session.add(behavior)
        customers.append((customer, behavior_data))

    db.session.commit()
    print('seed_core() complete.')
    return customers


def seed_predictions():
    from database.db import db
    from models.customer import Customer
    from models.prediction import Prediction
    from services.prediction_service import models_available, predict_both

    if not models_available():
        print('Models not trained yet - skipping historical prediction seeding.')
        print('Run: python ml/training/train_basic.py, then restart the server (or re-run this script).')
        return

    if Prediction.query.count() > 0:
        print('Predictions already seeded - skipping seed_predictions().')
        return

    rng = random.Random(7)
    customers = Customer.query.all()
    print(f'Generating historical predictions for {len(customers)} customers using the trained models...')

    now = datetime.now(timezone.utc)
    for customer in customers:
        if not customer.behavior:
            continue
        behavior = customer.behavior
        payload = {
            'age': customer.age, 'gender': customer.gender, 'device_type': customer.device_type,
            'browsing_time': behavior.browsing_time, 'pages_viewed': behavior.pages_viewed,
            'previous_purchases': behavior.previous_purchases, 'average_order_value': behavior.average_order_value,
            'number_of_sessions': behavior.number_of_sessions, 'cart_additions': behavior.cart_additions,
            'cart_abandonments': behavior.cart_abandonments, 'days_since_last_purchase': behavior.days_since_last_purchase,
            'customer_lifetime_value': behavior.customer_lifetime_value, 'discount_usage': behavior.discount_usage,
            'support_interactions': behavior.support_interactions,
        }
        result = predict_both(payload)
        # 1-3 historical predictions per customer, spread over the last 90 days,
        # so analytics charts (prediction trend, growth) have real spread.
        for _ in range(rng.randint(1, 3)):
            created_at = now - timedelta(days=rng.randint(0, 90), hours=rng.randint(0, 23))
            pred = Prediction(
                customer_id=customer.id,
                purchase_probability=result['purchase']['probability'],
                purchase_prediction=result['purchase']['prediction'],
                churn_probability=result['churn']['probability'],
                churn_risk=result['churn']['risk'],
                confidence=result['confidence'],
                engagement_score=result['engagement_score'],
                created_at=created_at,
            )
            pred.set_factors(result['factors'])
            pred.insight = result['insights'][0]
            db.session.add(pred)

    db.session.commit()
    print('seed_predictions() complete.')


def run_seed():
    seed_core()
    seed_predictions()


